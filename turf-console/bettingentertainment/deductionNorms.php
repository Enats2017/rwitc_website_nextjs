        <span style="font-size:10.0pt;font-family:Verdana"><b>(C)</b>&nbsp;&nbsp;&nbsp;&nbsp; The
          procedure for selection of bookmakers whose betting sheets would be
          considered for determining the percentage of deduction on WIN and PLACE
          in case of withdrawal of a horse/s shall be as under:-&nbsp;</span>
      </p>
      <p class="MsoNormal" style="text-align: justify; line-height: normal; margin-left: .5in; margin-right: 0in; margin-top: 0in">
        <span style="font-size:10.0pt;font-family:Verdana">(i)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; For the
          purpose of determining the current odds of withdrawn/non-starter horse,
          Auditors will take into consideration last recorded entry (closing odds)
