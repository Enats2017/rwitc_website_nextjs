<span class="about-eyebrow">History</span>
<h2>Timeline</h2>
<p class="about-subtitle">Key milestones in the history of the Club</p>
<hr class="about-divider" />

                         <p align="justify" >
                               <b>1798</b> - A two-day race meeting held in Bombay after raising funds via an appeal in local newspapers. 
                         </p>

                          <p align="justify" >
                               <b>1800</b> - Sir Charles Forbes, G Hall, A Campbell and P Haddow start Bombay Turf Club in Byculla Club Grounds acquired through the good offices of Dorabji Rustomji, the Patel of Bombay. 
                         </p>

                          <p align="justify" >
                               <b>1819</b> - The first horse race held in Pune with a 100-guinea cup donated by the British Resident — and later Governor of Bombay — the Hon. Mr Mountstuart Elphinstone, as the trophy — one year after the end of the Last Anglo-Maratha War and the Peshwa reign.
                         </p>

                          <p align="justify" >
                               <b>1830</b> - The Pune Race Course built on the present site in the Cantonment near the Empress Garden. 
                         </p>

                          <p align="justify" >
                              <b>1864</b> - Bombay Turf Club changes its name to Western India Turf Club. A move to a new venue is also mooted.
                         </p>

                          <p align="justify" >
                             <b>1870</b> - The Byculla Club Purse starts; out of it, are given prizes for the first time. Perhaps, this is the origin of the Byculla Club Cup.
                         </p>

                          <p align="justify" >
                             <b>1878</b> - Racing shifts to Mahalaxmi Flats, built on the marshy land donated by the Philanthropist and Industrialist Sir Cusrow N Wadia — under the direction and supervision of Major JE Hughes — but is abandoned after one season because of difficulty of access and foul odour from the open drain nearby.
                         </p>

                          <p align="justify" >
                             <b>1883</b> - Racing finally shifts to Mahalaxmi.
                         </p>

                          <p align="justify" >
                             <b>1886 - 1897</b> - Agreement reached with the Calcutta Turf Club "that no course in India be allowed to race under Rules without being controlled by either of the two Turf Authorities."
                         </p>

                          <p align="justify" >
                             <b>1923</b> - The Eclipse Stakes of India run for the first time.
                         </p>

                          <p align="justify" >
                              <b>1935</b> - HRH King George V, Emperor of India, grants permission to add the prefix "Royal" to the Club's name.
                         </p>

                          <p align="justify" >
                             <b>1936</b> - Electric clock installed.
                         </p>

                          <p align="justify" >
                            <b>1938</b> - The Apprentice Jockeys' School started under the guidance of the Stipendiary Stewards of the Club.
                         </p>

                          <p align="justify" >
                              <b>1942 - 43</b> - The Indian classics, restricted to horses bred in India, introduced. Princess Beautiful, a Maharaja of Baroda filly, wins the Indian 1000 Guineas, the Indian 2000 Guineas and the Indian Derby.
                         </p>

                          <p align="justify" >
                             <b>1949</b> - Kheem Singh is the first Indian jockey to win the Indian Derby, thus far dominated by foreign riders.
                         </p>

                          <p align="justify" >
                             <b>1961</b> - HRH Queen Elizabeth II of Great Britain visits Mahalaxmi. 
                         </p>

                          <p align="justify" >
                            <b>1963</b> - The inaugural Indian Invitation Cup held at Mahalaxmi. 
                         </p>

                         <p align="justify" >
                              <b>1965</b> - Rose Royale wins the Indian Fillies Triple Crown: 1000 Guineas, Indian Oaks, and Indian Derby.
                         </p>

                         <p align="justify" >
                             <b>1967</b> - Joint Mumbai-Pune Tote and inter-venue betting starts. Also, voice relay of announcements from the live centre to the ghost centre begins.
                         </p>

                         <p align="justify" >
                            <b>1971</b> - An all-time record jackpot of Rs.48,00,000/- won at Mahalaxmi by the Hindi film lyricist, Rajendra Krishnan. 
                         </p>

                         <p align="justify" >
                             <b>1974</b> - Interstate intervenue betting between Mumbai/Pune and Bangalore begins. 
                         </p>

                         <p align="justify" >
                            <b>1985</b> - The first running of the McDowell Indian Derby.
                         </p>

                          <p align="justify" >
                            <b>1987</b> - RWITC enters into an agreement with the Amateur Riders' Club to run the Apprentice Jockeys' School. 
                         </p>

                          <p align="justify" >
                            <b>1990</b> - India's first Million for 3-year olds is the Poonawalla Breeders' Million. Le Gris Cheval wins the inaugural edition. It later reaches the Grade III status (1994), then Grade II (1995) and finally Grade I (1996).
                         </p>

                          <p align="justify" >
                            <b>2002</b> - Inter-venue betting with Hyderabad starts.
                         </p>

                          <p align="justify" >
                           <b>2002</b> - Ten Sports starts live telecast of racing action at Mahalaxmi.
                         </p>

                          <p align="justify" >
                            <b>2002</b> - The Western India Race Horse Owners' Association (WIRHOA) starts the WIRHOA Racing Awards for owners and horses.
                         </p>

                          <p align="justify" >
                            <b>2002</b> - State-of-the-art photo finish camera installed.
                         </p>

                          <p align="justify" >
                            <b>2004</b> - Innovative Monsoon track preparation (laying the tan outside it from 1400 metres to the winning post) to prevent horses running on the far out during heavy rains do not hit hard on the ground.
                         </p>

                          <p align="justify" >
                           <b>2006</b> - For the first time ever, 7 multinationals sponsor the entire December race day card.
                         </p>

                          <p align="justify" >
                            <b>2008</b> - Equine influenza epidemic in Pune stables. Mumbai 2008 - 2009 season postponed.
                         </p>

                         <p align="justify" >
                            <b>2008</b> - Fire destroys third deck of the Members Stand in July 2008. (Restored in September 2009.)
                         </p>

                         <p align="justify" >
                            <b>2009</b> - The new Club House with Gym &amp; Card Room for members inaugrated on Dec 6th 2009.
                         </p>
            
